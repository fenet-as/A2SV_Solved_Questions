class Solution:
    def countCommas(self, n: int) -> int:
        """ 
            * 1000 - 999,999
            n - 999 

            * 1,000,000 - 999,999,999
            n - 999,999 * 2 
            + 999,999 - 999

            *1,000,000,000 - 999,999,999,999
            n - 999,999,999 * 3
            + 999,999,999 - 999,999 * 2
            + 999,999 - 999



            999,999
            1,000,000

            999,999,999
            --> 999,000,000*2 + 999,000 = 1,998,999,000


            1,000,000,000 -- 999,999,999 * 3
            -- 999

        """
        
        def find(n):
            if n < 1000:return 0

            elif n < 1000000:
                return n - 999 + find(999)

            elif n < 1000000000:
                return (n - 999999)*2 + find(999999)
            
            elif n < 1000000000000:
                return (n - 999999999)* 3 + find(999999999)

            elif n < 1000000000000000:
                return (n - 999999999999) * 4 + find(999999999999)

            elif n < 1000000000000000000:
                return (n - 999999999999999) * 5 + find(999999999999999)

        return find(n)

    